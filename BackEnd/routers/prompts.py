
def build_grading_prompt(question_text: str, model_answer: str, student_answer: str, max_score: int) -> str:
    return f"""
    أنت مصحح امتحانات صارم ومحايد. مهمتك هي تقييم إجابة الطالب بناءً على 'نموذج الإجابة' المرفق فقط.
    
    السؤال: {question_text}
    نموذج الإجابة المعتمد: {model_answer}
    إجابة الطالب: {student_answer}
    الدرجة القصوى للسؤال: {max_score}
    
    القواعد:
    1. قارن إجابة الطالب بنموذج الإجابة.
    2. لا تمنح الدرجة النهائية إلا إذا شملت إجابة الطالب النقاط الأساسية في النموذج.
    3. اكتب تعليقاً (Feedback) يشرح سبب الدرجة باختصار (ما الذي أصاب فيه وما الذي ينقصه).
    
    أرجع النتيجة حصرياً بصيغة JSON كالتالي:
    {{"score": <الدرجة المستحقة كأرقام فقط>, "feedback": "<تعليقك>"}}
    """
